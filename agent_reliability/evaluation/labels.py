"""Heuristic + manual failure labels for a run directory.

Files in runs/<run>/:
  failures_auto.json   heuristic labels with evidence (regenerated by `analyze`)
  labels_manual.csv    your labels: task_id,repeat,category,notes. Edit it in any spreadsheet
                       or text editor, or fill it interactively with `label`
  failures.csv         merged view: final category = manual if present, else heuristic
"""

from __future__ import annotations

import csv
import json
import textwrap
from pathlib import Path

from ..benchmark.runner import load_results
from ..benchmark.tasks import load_tasks
from ..trace import load_trace
from .failure_analysis import CATEGORIES, NON_AGENT, FailureLabel, analyze_run

MANUAL_FIELDS = ["task_id", "repeat", "category", "notes"]


def _load_traces(run_dir: Path, results: list[dict]) -> dict[tuple[str, int], dict]:
    return {(r["task_id"], r["repeat"]): load_trace(run_dir / "traces" / f"{r['task_id']}__r{r['repeat']}.json")
            for r in results}


def analyze(run_dir: Path) -> list[dict]:
    run_dir = Path(run_dir)
    results = load_results(run_dir)
    tasks = {t.id: t for t in load_tasks()}
    labels = analyze_run(tasks, _load_traces(run_dir, results), results)
    (run_dir / "failures_auto.json").write_text(json.dumps([l.to_dict() for l in labels], indent=2), encoding="utf-8")
    merged = merge_labels(run_dir)
    return merged


def load_manual(run_dir: Path) -> dict[tuple[str, int], dict]:
    path = Path(run_dir) / "labels_manual.csv"
    if not path.exists():
        return {}
    out = {}
    with path.open(encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            cat = (row.get("category") or "").strip()
            if not cat:
                continue
            if cat not in CATEGORIES + NON_AGENT:
                raise ValueError(f"{path}: unknown category {cat!r} for {row['task_id']} (valid: {CATEGORIES})")
            out[(row["task_id"], int(row.get("repeat") or 0))] = {"category": cat, "notes": row.get("notes", "")}
    return out


def save_manual(run_dir: Path, manual: dict[tuple[str, int], dict]) -> None:
    path = Path(run_dir) / "labels_manual.csv"
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=MANUAL_FIELDS)
        w.writeheader()
        for (tid, rep), v in sorted(manual.items()):
            w.writerow({"task_id": tid, "repeat": rep, "category": v["category"], "notes": v.get("notes", "")})


def merge_labels(run_dir: Path) -> list[dict]:
    run_dir = Path(run_dir)
    auto_path = run_dir / "failures_auto.json"
    auto = json.loads(auto_path.read_text(encoding="utf-8")) if auto_path.exists() else []
    manual = load_manual(run_dir)
    merged = []
    for a in auto:
        key = (a["task_id"], a["repeat"])
        m = manual.get(key)
        merged.append({
            "task_id": a["task_id"], "repeat": a["repeat"],
            "heuristic_category": a["category"],
            "manual_category": m["category"] if m else "",
            "final_category": m["category"] if m else a["category"],
            "label_source": "manual" if m else "heuristic",
            "evidence": " | ".join(a["evidence"]),
            "manual_notes": m.get("notes", "") if m else "",
        })
    with (run_dir / "failures.csv").open("w", encoding="utf-8", newline="") as f:
        fields = ["task_id", "repeat", "heuristic_category", "manual_category", "final_category",
                  "label_source", "evidence", "manual_notes"]
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(merged)
    return merged


