def format_trace(trace: dict, width: int = 110, max_out: int = 400) -> str:
    lines = [f"TASK {trace['task_id']} [{trace['condition']}] status={trace['status']}",
             textwrap.fill(trace["task"], width)]
    for s in trace["steps"]:
        head = (f"--- step {s['index']} ({s['kind']})" + (f" [{s['note']}]" if s.get("note") else "")
                + (" [EMPTY RESPONSE → nudged]" if s.get("nudged") else ""))
        lines.append(head)
        if s.get("reasoning"):
            lines.append(textwrap.indent(textwrap.shorten(s["reasoning"], 1200, placeholder=" …"), "  thought: "))
        for c in s.get("tool_calls", []):
            lines.append(f"  → {c['name']}({json.dumps(c['args'])[:300]})")
            res = ("ERROR: " + c["error"]) if c.get("error") else str(c.get("output"))
            lines.append("    ← " + textwrap.shorten(res.replace("\n", " ⏎ "), max_out, placeholder=" …"))
        if s.get("proposed_answer") is not None:
            lines.append(f"  → final_answer({s['proposed_answer']!r})")
    lines.append(f"FINAL ANSWER: {trace.get('final_answer')!r}")
    return "\n".join(lines)


def interactive_label(run_dir: Path, relabel: bool = False, input_fn=input) -> None:
    run_dir = Path(run_dir)
    merged = analyze(run_dir)
    manual = load_manual(run_dir)
    tasks = {t.id: t for t in load_tasks()}
    todo = [m for m in merged if relabel or (m["task_id"], m["repeat"]) not in manual]
    print(f"{len(todo)} failed runs to label ({len(merged)} failures total). "
          "Enter = accept suggestion, number = pick category, s = skip, q = quit.\n")
    menu = "  " + "  ".join(f"[{i + 1}] {c}" for i, c in enumerate(CATEGORIES + NON_AGENT))
    for m in todo:
        tid, rep = m["task_id"], m["repeat"]
        trace = load_trace(run_dir / "traces" / f"{tid}__r{rep}.json")
        print("=" * 110)
        print(format_trace(trace))
        print(f"EXPECTED: {tasks[tid].answer!r}" + (f"   (trap: {tasks[tid].trap})" if tasks[tid].trap else ""))
        print(f"\nHeuristic suggestion: {m['heuristic_category']}  ← {m['evidence']}")
        print(menu)
        choice = input_fn("category> ").strip().lower()
        if choice == "q":
            break
        if choice == "s":
            continue
        options = CATEGORIES + NON_AGENT
        if choice == "":
            cat = m["heuristic_category"]
        elif choice.isdigit() and 1 <= int(choice) <= len(options):
            cat = options[int(choice) - 1]
        elif choice in options:
            cat = choice
        else:
            print("  unrecognized, skipping")
            continue
        notes = input_fn("notes (optional)> ").strip()
        manual[(tid, rep)] = {"category": cat, "notes": notes}
        save_manual(run_dir, manual)  # save after every label so quitting loses nothing
    merge_labels(run_dir)
    print(f"\nSaved manual labels to {run_dir / 'labels_manual.csv'}")


__all__ = ["analyze", "interactive_label", "load_manual", "merge_labels", "format_trace", "FailureLabel"]
